import type { Prisma } from "@prisma/client";

import { prisma } from "@/lib/db/prisma";
import { computeOccurrences } from "@/lib/preventive/compute-occurrences";
import { TYPE_CODE_TO_OM_TASK_FLAGS } from "@/lib/preventive/constants";
import { isPreventivePersistenceReady } from "@/lib/preventive/persistence";
import { toPlanScheduleInput } from "@/lib/preventive/schedule-input";
import { addDaysIso, todayTunisApprox } from "@/lib/preventive/preview-adapter";

/**
 * Lot 4 — Génération des ordres de maintenance (OM) préventifs.
 *
 * Pour chaque plan ACTIF, les occurrences calculées sur l'horizon [aujourd'hui, +N jours]
 * sont persistées (MaintenanceOccurrence, idempotence via occurrenceKey) puis rattachées
 * à l'OM journalier (un OM par jour, `OM-YYYY-MM-DD`) : ligne machine + tâche préventive.
 */

/** Horizon maximal de génération d'OM (jours), même si le plan prévoit plus. */
export const MAX_GENERATION_HORIZON_DAYS = 14;

const planInclude = {
  maintenanceType: { select: { code: true, label: true } },
  scheduleRules: { orderBy: { sortOrder: "asc" } },
} satisfies Prisma.PreventiveMaintenancePlanInclude;

type PlanWithRules = Prisma.PreventiveMaintenancePlanGetPayload<{ include: typeof planInclude }>;

export type GenerationResult = {
  plans: number;
  occurrencesCreated: number;
  tasksCreated: number;
  ordersCreated: number;
  skippedClosedOrders: number;
  markedDone: number;
  markedOverdue: number;
};

const dbDate = (iso: string) => new Date(`${iso}T00:00:00.000Z`);
/** Midi heure de Tunis → même jour calendaire quel que soit le fuseau serveur. */
const orderPlannedDate = (iso: string) => new Date(`${iso}T12:00:00+01:00`);

type OrderCache = Map<string, { id: string; writable: boolean }>;

async function ensureDailyOrder(
  tx: Prisma.TransactionClient,
  dayKey: string,
  cache: OrderCache,
  result: GenerationResult,
) {
  const cached = cache.get(dayKey);
  if (cached) return cached;
  const reference = `OM-${dayKey}`;
  let order = await tx.maintenanceOrder.findFirst({
    where: { OR: [{ dayKey }, { reference }] },
    select: { id: true, status: true },
  });
  if (!order) {
    order = await tx.maintenanceOrder.create({
      data: {
        reference,
        dayKey,
        plannedDate: orderPlannedDate(dayKey),
        autoGenerated: true,
        observationComment: "Généré automatiquement par le planning préventif.",
      },
      select: { id: true, status: true },
    });
    result.ordersCreated += 1;
  }
  const entry = { id: order.id, writable: order.status === "ACTIVE" };
  cache.set(dayKey, entry);
  return entry;
}

async function generateForPlan(plan: PlanWithRules, cache: OrderCache, result: GenerationResult) {
  if (plan.status !== "ACTIVE") return;
  const today = todayTunisApprox();
  const horizonDays = Math.max(1, Math.min(plan.generationHorizonDays, MAX_GENERATION_HORIZON_DAYS));
  const { occurrences } = computeOccurrences(toPlanScheduleInput(plan), {
    from: today,
    to: addDaysIso(today, horizonDays - 1),
  });
  if (occurrences.length === 0) return;

  const existing = await prisma.maintenanceOccurrence.findMany({
    where: { occurrenceKey: { in: occurrences.map((o) => o.occurrenceKey) } },
    select: { occurrenceKey: true, maintenanceOrderTaskId: true, status: true },
  });
  const existingByKey = new Map(existing.map((e) => [e.occurrenceKey, e]));
  const flags = TYPE_CODE_TO_OM_TASK_FLAGS[plan.maintenanceType.code] ?? {};

  for (const occ of occurrences) {
    const prev = existingByKey.get(occ.occurrenceKey);
    if (prev?.maintenanceOrderTaskId || (prev && prev.status !== "PLANNED")) continue;

    const base = {
      planId: plan.id,
      planVersion: plan.version,
      occurrenceKey: occ.occurrenceKey,
      periodKey: occ.periodKey,
      occurrenceIndex: occ.occurrenceIndex,
      theoreticalDate: dbDate(occ.theoreticalDate),
      theoreticalTime: occ.theoreticalTime,
      plannedDate: occ.plannedDate ? dbDate(occ.plannedDate) : null,
      plannedTime: occ.plannedTime,
      plannedAtUtc: occ.plannedAtUtc ? new Date(occ.plannedAtUtc) : null,
      sundayAdjustment: occ.sundayAdjustment,
    };

    if (occ.status === "SKIPPED" || !occ.plannedDate) {
      await prisma.maintenanceOccurrence.upsert({
        where: { occurrenceKey: occ.occurrenceKey },
        create: { ...base, status: "SKIPPED" },
        update: { ...base, status: "SKIPPED" },
      });
      if (!prev) result.occurrencesCreated += 1;
      continue;
    }

    const plannedDate = occ.plannedDate;
    await prisma.$transaction(async (tx) => {
      const order = await ensureDailyOrder(tx, plannedDate, cache, result);
      if (!order.writable) {
        result.skippedClosedOrders += 1;
        await tx.maintenanceOccurrence.upsert({
          where: { occurrenceKey: occ.occurrenceKey },
          create: { ...base, status: "PLANNED" },
          update: { ...base },
        });
        return;
      }

      const line = await tx.maintenanceOrderLine.upsert({
        where: { maintenanceOrderId_machineId: { maintenanceOrderId: order.id, machineId: plan.machineId } },
        create: { maintenanceOrderId: order.id, machineId: plan.machineId, ...flags },
        update: flags,
        select: { id: true },
      });

      const task = await tx.maintenanceOrderTask.create({
        data: {
          maintenanceOrderLineId: line.id,
          maintenanceTypeId: plan.maintenanceTypeId,
          title: plan.title,
          instructions: plan.instructions,
          plannedTime: occ.plannedTime,
          estimatedDurationMin: plan.estimatedDurationMin,
          assigneeTechnicianId: plan.assigneeTechnicianId,
          source: "PREVENTIVE_PLAN",
        },
        select: { id: true },
      });

      const links = {
        status: "GENERATED" as const,
        maintenanceOrderId: order.id,
        maintenanceOrderTaskId: task.id,
      };
      await tx.maintenanceOccurrence.upsert({
        where: { occurrenceKey: occ.occurrenceKey },
        create: { ...base, ...links },
        update: { ...base, ...links },
      });
    });
    if (!prev) result.occurrencesCreated += 1;
    result.tasksCreated += 1;
  }

  await prisma.preventiveMaintenancePlan.update({
    where: { id: plan.id },
    data: { lastGeneratedAt: new Date() },
  });
}

/**
 * Synchronise les statuts dérivés : DONE si la tâche / la ligne OM est réalisée,
 * OVERDUE si l'échéance est passée sans réalisation.
 */
export async function syncOccurrenceStatuses(planId?: string) {
  const today = dbDate(todayTunisApprox());
  const scope = planId ? { planId } : {};
  const done = await prisma.maintenanceOccurrence.updateMany({
    where: {
      ...scope,
      status: { in: ["GENERATED", "OVERDUE"] },
      OR: [
        { maintenanceOrderTask: { status: "DONE" } },
        { maintenanceOrderTask: { maintenanceOrderLine: { maintenanceLog: { isNot: null } } } },
        { maintenanceOrder: { status: "COMPLETED" } },
      ],
    },
    data: { status: "DONE", completedAt: new Date() },
  });
  const overdue = await prisma.maintenanceOccurrence.updateMany({
    where: { ...scope, status: { in: ["PLANNED", "GENERATED"] }, plannedDate: { lt: today } },
    data: { status: "OVERDUE" },
  });
  return { markedDone: done.count, markedOverdue: overdue.count };
}

/**
 * Supprime les occurrences futures non réalisées d'un plan (et leurs tâches OM ouvertes),
 * avant régénération suite à une modification / suspension du plan.
 */
export async function resetFuturePlanOccurrences(planId: string) {
  const today = dbDate(todayTunisApprox());
  const future = await prisma.maintenanceOccurrence.findMany({
    where: {
      planId,
      plannedDate: { gte: today },
      status: { in: ["PLANNED", "GENERATED", "SKIPPED"] },
    },
    select: {
      id: true,
      maintenanceOrderTask: {
        select: { id: true, status: true, maintenanceOrderLineId: true },
      },
    },
  });
  const removable = future.filter((o) => !o.maintenanceOrderTask || o.maintenanceOrderTask.status === "OPEN");
  if (removable.length === 0) return 0;

  const taskIds = removable.flatMap((o) => (o.maintenanceOrderTask ? [o.maintenanceOrderTask.id] : []));
  const lineIds = [
    ...new Set(removable.flatMap((o) => (o.maintenanceOrderTask ? [o.maintenanceOrderTask.maintenanceOrderLineId] : []))),
  ];

  await prisma.$transaction(async (tx) => {
    await tx.maintenanceOccurrence.deleteMany({ where: { id: { in: removable.map((o) => o.id) } } });
    if (taskIds.length) await tx.maintenanceOrderTask.deleteMany({ where: { id: { in: taskIds } } });
    // Retire les lignes machine devenues vides (créées par le planning, sans intervention saisie).
    if (lineIds.length) {
      await tx.maintenanceOrderLine.deleteMany({
        where: {
          id: { in: lineIds },
          tasks: { none: {} },
          maintenanceLog: { is: null },
          maintenanceOrder: { status: "ACTIVE", autoGenerated: true },
        },
      });
    }
  });
  return removable.length;
}

/** Génère les OM préventifs pour un plan (après création / modification). */
export async function generatePreventiveOrdersForPlan(planId: string): Promise<GenerationResult> {
  const result = emptyResult();
  if (!(await isPreventivePersistenceReady())) return result;
  const plan = await prisma.preventiveMaintenancePlan.findUnique({ where: { id: planId }, include: planInclude });
  if (!plan) return result;
  result.plans = 1;
  await generateForPlan(plan, new Map(), result);
  Object.assign(result, await syncOccurrenceStatuses(planId));
  return result;
}

/** Génère les OM préventifs pour tous les plans actifs (cron quotidien / bouton manuel). */
export async function generateAllPreventiveOrders(): Promise<GenerationResult> {
  const result = emptyResult();
  if (!(await isPreventivePersistenceReady())) return result;
  const plans = await prisma.preventiveMaintenancePlan.findMany({
    where: { status: "ACTIVE" },
    include: planInclude,
    orderBy: { createdAt: "asc" },
  });
  const cache: OrderCache = new Map();
  for (const plan of plans) {
    try {
      await generateForPlan(plan, cache, result);
      result.plans += 1;
    } catch (err) {
      console.error(`[preventive-generate] plan ${plan.id}`, err);
    }
  }
  Object.assign(result, await syncOccurrenceStatuses());
  return result;
}

function emptyResult(): GenerationResult {
  return {
    plans: 0,
    occurrencesCreated: 0,
    tasksCreated: 0,
    ordersCreated: 0,
    skippedClosedOrders: 0,
    markedDone: 0,
    markedOverdue: 0,
  };
}
